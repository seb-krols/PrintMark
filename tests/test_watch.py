import sys
import time
from datetime import UTC, datetime
from pathlib import Path

import pytest

from basemark.config import Settings, save_settings
from basemark.notify import texts
from basemark.watch import Watcher, export_folders, inspect, running, stop

FIXTURE = Path(__file__).parent / "fixtures" / "prusaslicer-2.8.1-pla-relative.gcode"


def export(folder: Path, name="part.gcode", *, hook="", preset="0.20mm SPEED @MK4IS 0.4"):
    text = FIXTURE.read_text().replace("; post_process = \n", f"; post_process = {hook}\n")
    text = text.replace("; print_settings_id = \n", f"; print_settings_id = {preset}\n")
    path = folder / name
    path.write_text(text)
    return path


def test_unhooked_export_names_the_preset(tmp_path):
    reason = inspect(export(tmp_path))
    assert "“0.20mm SPEED @MK4IS 0.4” doesn't run BaseMark" in reason


def test_exports_basemark_saw_or_other_slicers_are_ignored(tmp_path):
    hooked = export(tmp_path, hook='"C:\\Programs\\BaseMark\\basemark.exe"')
    assert inspect(hooked) is None
    stamped = tmp_path / "stamped.gcode"
    stamped.write_text("; BASEMARK stamp PLA; layers=2\n" + export(tmp_path).read_text())
    assert inspect(stamped) is None
    other = tmp_path / "bambu.gcode"
    other.write_text("; generated by BambuStudio\nG1 X1\n")
    assert inspect(other) is None


def test_binary_gcode_is_reported(tmp_path):
    path = tmp_path / "part.bgcode"
    path.write_bytes(b"GCDE\x01\x00\x00\x00" + bytes(64))
    assert "binary G-code" in inspect(path)
    path.write_bytes(b"not a bgcode")
    assert inspect(path) is None


@pytest.fixture
def setup(tmp_path, monkeypatch):
    home, out, data = tmp_path / "home", tmp_path / "USB", tmp_path / "PrusaSlicer"
    for folder in (home / "Downloads", out, data):
        folder.mkdir(parents=True)
    (data / "PrusaSlicer.ini").write_text(f"last_output_path = {out}\n[presets]\nprint = x\n")
    monkeypatch.setattr(Path, "home", classmethod(lambda cls: home))
    config = tmp_path / "BaseMark" / "config.toml"
    config.parent.mkdir()
    return config, data, out, home / "Downloads"


def test_folders_follow_prusaslicer(setup):
    config, data, out, downloads = setup
    assert export_folders(data) == [out, downloads]


def test_new_export_is_reported_once_it_stops_changing(setup, notices):
    config, data, out, downloads = setup
    old = export(out, "old.gcode")
    os.utime(old, (time.time() - 3600, time.time() - 3600))
    watcher = Watcher(config, data=data, started=time.time() - 60)
    path = export(out)
    assert watcher.tick() == []  # first sight: it may still be written
    found = watcher.tick()
    assert [p for p, _ in found] == [path]
    assert notices == ["unstamped"]
    assert watcher.tick() == []  # each export warns once
    export(downloads, "other.gcode", hook="basemark.exe")
    watcher.tick()
    assert watcher.tick() == []


def test_warning_can_be_switched_off(setup, notices):
    config, data, out, _ = setup
    save_settings(config, Settings(warn_unstamped=False))
    watcher = Watcher(config, data=data, started=time.time() - 60)
    export(out)
    watcher.tick()
    assert watcher.tick() == []
    assert notices == []


def test_no_second_notice_when_basemark_reported_the_export(setup, notices):
    config, data, out, _ = setup
    report = {"timestamp": datetime.now(UTC).isoformat(), "source": str(out / "part.bgcode")}
    (config.parent / "last-export.json").write_text(json.dumps(report))
    watcher = Watcher(config, data=data, started=time.time() - 60)
    (out / "part.bgcode").write_bytes(b"GCDE" + bytes(16))
    watcher.tick()
    assert watcher.tick() == []


def test_single_background_process_and_stop(tmp_path):
    config = tmp_path / "config.toml"
    command = [sys.executable, "-m", "basemark", "--watch", "--config", str(config)]
    first = subprocess.Popen(command)
    try:
        for _ in range(80):
            if running(config):
                break
            time.sleep(0.1)
        assert running(config)
        assert subprocess.run(command, timeout=20).returncode == 0  # already running: exits
        assert stop(config)
        assert first.wait(timeout=10) == 0
    finally:
        first.kill()


